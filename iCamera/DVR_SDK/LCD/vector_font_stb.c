static stbtt_fontinfo g_font;    // 字体信息
static int g_font_initialized = 0;

/**
 * @brief 初始化 stb_truetype 字体引擎
 * @return 0 成功，-1 失败
 */
int STB_Font_Init(void)
{
    if (g_font_initialized) {
        return 0;
    }

    if (!stbtt_InitFont(&g_font, font_ttf, 0)) {
        LCD_ERR("stbtt_InitFont failed");
        return -1;
    }

    g_font_initialized = 1;
    return 0;
}

/**
 * @brief 反初始化 stb_truetype 字体引擎
 * @note stb_truetype 本身无动态分配，此函数仅重置标志位以便重新初始化
 */
void STB_Font_Deinit(void)
{
    if (g_font_initialized) {
        /* stb_truetype 不提供显式释放接口，仅重置标志 */
        g_font_initialized = 0;
        LCD_DBG("STB Font engine deinitialized");
    }
}

/**
 * @brief 获取字符的度量信息（宽度和底部下伸量）
 * @param unicode      Unicode 字符码
 * @param pixel_h      渲染目标高度（像素）
 * @param out_advance  输出：字符的横向步进距离（像素）
 * @param out_descender 输出：基线到底部的距离（正值，如 'y' 的下伸部分）
 * @return 0 成功，-1 失败
 */
static int STB_GetCharMetrics(uint32_t unicode, int pixel_h,
                       int* out_advance, int* out_descender)
{
    if (!g_font_initialized) {
        return -1;
    }

    float scale = stbtt_ScaleForPixelHeight(&g_font, pixel_h);
    int advance, lsb;
    stbtt_GetCodepointHMetrics(&g_font, unicode, &advance, &lsb);
    *out_advance = (int)(advance * scale + 0.5f);

    int x0, y0, x1, y1;
    stbtt_GetCodepointBitmapBox(&g_font, unicode, scale, scale, &x0, &y0, &x1, &y1);
    *out_descender = y1;   /* y1 为正值，表示基线到底部的距离 */

    return 0;
}

/**
 * @brief 渲染 Unicode 字符为灰度位图
 * @param unicode  字符代码
 * @param pixel_h  目标像素高度（如 70）
 * @param out_bitmap 输出位图指针（需调用者 free）
 * @param out_w     输出宽度
 * @param out_h     输出高度
 * @param out_xoff  水平偏移（绘制时 x 坐标需加上此值）
 * @param out_yoff  垂直偏移（绘制时 y 坐标需加上此值）
 * @return 0 成功，-1 失败
 */
static int STB_RenderChar(uint32_t unicode, int pixel_h,
                        unsigned char** out_bitmap, int* out_w, int* out_h,
                        int* out_xoff, int* out_yoff, int* out_advance)
{
    if (!g_font_initialized) {
        return -1;
    }
    float scale = stbtt_ScaleForPixelHeight(&g_font, pixel_h);

    // 特殊处理空格：不渲染位图，但需要获取 advance
    if (unicode == 0x20)
    {
        int advance, lsb;
        stbtt_GetCodepointHMetrics(&g_font, unicode, &advance, &lsb);
        *out_advance = (int)(advance * scale + 0.5f);
        *out_bitmap = NULL;
        *out_w = *out_h = *out_xoff = *out_yoff = 0;
        return 0;
    }

    unsigned char* bitmap = stbtt_GetCodepointBitmap(&g_font, 0, scale, unicode, out_w, out_h, out_xoff, out_yoff);
    if (!bitmap) {
        LCD_ERR("stbtt_GetCodepointBitmap failed for U+%04X", unicode);
        return -1;
    }

    // 获取 advance 和 descender
    int advance, lsb;
    stbtt_GetCodepointHMetrics(&g_font, unicode, &advance, &lsb);
    *out_advance = (int)(advance * scale + 0.5f);
    *out_bitmap = bitmap;
    return 0;
}

/**
 * @brief 绘制灰度位图到 RGB565 缓冲区
 * @param dst        目标缓冲区
 * @param dst_w      目标宽度（像素）
 * @param dst_h      目标高度
 * @param x,y        绘制位置（左上角）
 * @param bitmap     灰度位图（每像素1字节，0=透明，255=前景）
 * @param bmp_w      位图宽度
 * @param bmp_h      位图高度
 * @param fg_color   前景色（RGB565）
 * @param bg_color   背景色（RGB565，COLOR_TRANSPARENT表示透明）
 */
// 绘制灰度位图到 RGB565 缓冲区（使用字节操作确保小端正确）
static void draw_gray_bitmap_rgb565(uint16_t* dst, int dst_w, int dst_h,
                                    int x, int y, const unsigned char* bitmap, 
                                    int bmp_w, int bmp_h, uint16_t fg_color, uint16_t bg_color) {
    // 边界裁剪
    int startX = (x < 0) ? 0 : x;
    int startY = (y < 0) ? 0 : y;
    int endX = (x + bmp_w > dst_w) ? dst_w : x + bmp_w;
    int endY = (y + bmp_h > dst_h) ? dst_h : y + bmp_h;

    for (int row = startY; row < endY; row++) {
        int srcY = row - y;
        if (srcY < 0 || srcY >= bmp_h) continue;
        const unsigned char* srcRow = bitmap + srcY * bmp_w;
        uint16_t* dstRow = dst + row * dst_w + startX;
        for (int col = startX; col < endX; col++) {
            int srcX = col - x;
            if (srcX < 0 || srcX >= bmp_w) continue;
            uint8_t alpha = srcRow[srcX];
            if (alpha < 80) { /* 透明度阈值，可调整 */
                if (bg_color != COLOR_TRANSPARENT) {
                    dstRow[col - startX] = bg_color;
                }
            } else if (alpha == 255) {
                dstRow[col - startX] = fg_color;
            } else {
                uint16_t blended = blend_rgb565(fg_color, dstRow[col - startX], alpha);
                dstRow[col - startX] = blended;
            }
        }
    }
}

// 计算字符串的宽度、高度、基线（基于指定像素高度）
int STB_ComputeStringSize(const uint16_t *TextUnicode, int pixel_h,
                                int* out_width, int* out_height, int* out_baseline_y)
{
    if (!g_font_initialized || !TextUnicode || !out_width || !out_height || !out_baseline_y) {
        return -1;
    }

    int total_width = 0;
    int min_y = 0;   /* 顶部相对于基线的偏移（负值） */
    int max_y = 0;   /* 底部相对于基线的偏移（正值） */
    int advance, descender;

    for (int i = 0; TextUnicode[i] != 0; i++) {
        uint32_t unicode = TextUnicode[i];
        if (STB_GetCharMetrics(unicode, pixel_h, &advance, &descender) == 0) {
            total_width += advance;
            float scale = stbtt_ScaleForPixelHeight(&g_font, pixel_h);
            int x0, y0, x1, y1;
            stbtt_GetCodepointBitmapBox(&g_font, unicode, scale, scale, &x0, &y0, &x1, &y1);
            if (y0 < min_y) min_y = y0;
            if (y1 > max_y) max_y = y1;
        }
    }

    *out_width = total_width;
    *out_height = max_y - min_y;
    *out_baseline_y = -min_y;
    return 0;
}

/**
 * @brief 绘制单个 Unicode 字符（基于基线对齐）
 * @param dst           目标 RGB565 缓冲区
 * @param dst_w         缓冲区宽度（像素）
 * @param dst_h         缓冲区高度（像素）
 * @param x             字符原点的 X 坐标（字符最左侧）
 * @param y             字符原点的 Y 坐标（此参数保留但未使用，可忽略）
 * @param unicode       要绘制的 Unicode 字符
 * @param pixel_h       渲染目标高度（像素）
 * @param fg_color      前景色（RGB565）
 * @param bg_color      背景色（COLOR_TRANSPARENT 表示透明）
 * @param baseline_y    基线在屏幕上的 Y 坐标
 * @return 字符的实际前进量（advance + letter_spacing），失败返回 -1
 */
int STB_DrawChar(uint16_t* dst, int dst_w, int dst_h,
                 int x, int y, uint32_t unicode, int pixel_h,
                 uint16_t fg_color, uint16_t bg_color, int baseline_y)
{
    if (!g_font_initialized) {
        return -1;
    }

    unsigned char* bitmap = NULL;
    int w, h, xoff, yoff, advance;
    if (STB_RenderChar(unicode, pixel_h, &bitmap, &w, &h, &xoff, &yoff, &advance) != 0) {
        return -1;
    }

    int draw_x = x + xoff;
    int draw_y = baseline_y + yoff;

    if (bitmap != NULL && w > 0 && h > 0) {
        draw_gray_bitmap_rgb565(dst, dst_w, dst_h,
                                draw_x, draw_y,
                                bitmap, w, h,
                                fg_color, bg_color);
        free(bitmap);
    }

    return advance;
}

