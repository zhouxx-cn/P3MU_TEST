#include <stdio.h>
#include <limits.h>

#include "logging.h"

#ifdef USE_LOG
unsigned char logname[LOGNAME_SIZE];

void log_message(int level, const char *format, ...)
{
	va_list args;

	va_start(args, format);
	vsyslog(level, format, args);
	va_end(args);
}
#endif
